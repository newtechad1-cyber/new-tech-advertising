function normalizePath(pathname) {
  const value = String(pathname || "/").split(/[?#]/, 1)[0] || "/";
  if (value === "/") return "/";
  return "/" + value.replace(/^\/+/, "").replace(/\/+$/, "").toLowerCase();
}

function clip(value, maxLength) {
  const text = String(value || "").replace(/\s+/g, " ").trim();
  if (text.length <= maxLength) return text;
  return text.slice(0, maxLength - 1).replace(/\s+\S*$/, "") + "…";
}

function canonicalUrl(pathname) {
  return SITE_ORIGIN + (pathname === "/" ? "" : pathname);
}

export function getCollectionSearchMetadata(collectionSlug, collection) {
  const key = String(collectionSlug || "").toLowerCase();
  const override = COLLECTION_SEARCH[key];
  const title = override ? override.title : (collection && collection.title) || "Small Business Learning";
  const description = override ? override.description : (collection && collection.description) || DEFAULT_SEO.description;
  const path = "/knowledge/" + key;
  return {
    title: clip(title + " | NTA Knowledge Library", 72),
    description: clip(description, 158),
    canonical: canonicalUrl(path),
    noIndex: false,
  };
}

export function getLessonSearchMetadata(collectionSlug, lesson) {
  const collectionKey = String(collectionSlug || "").toLowerCase();
  const lessonSlug = String(lesson && lesson.slug || "").toLowerCase();
  const title = lesson && lesson.searchTitle
    ? lesson.searchTitle
    : (LESSON_SEARCH_TITLES[lessonSlug] || (lesson && lesson.title) || "Small Business Lesson");
  const description = lesson && lesson.searchDescription
    ? lesson.searchDescription
    : (lesson && lesson.description) || DEFAULT_SEO.description;
  const path = "/knowledge/" + collectionKey + "/" + lessonSlug;
  return {
    title: title + " | NTA Knowledge Library",
    description: clip(description, 158),
    canonical: canonicalUrl(path),
    noIndex: false,
  };
}

export function getSeoMetadata(pathname) {
  const normalized = normalizePath(pathname);
  const legacyCanonical = LEGACY_CANONICALS[normalized];
  const canonicalPath = legacyCanonical || normalized;

  if (STATIC_SEO[canonicalPath]) {
    return {
      ...DEFAULT_SEO,
      ...STATIC_SEO[canonicalPath],
      canonical: canonicalUrl(canonicalPath),
      routeSpecific: true,
    };
  }

  const segments = canonicalPath.split("/").filter(Boolean);
  if (segments[0] === "knowledge" && segments[1]) {
    if (segments.length === 2 && COLLECTION_SEARCH[segments[1]]) {
      const collection = COLLECTION_SEARCH[segments[1]];
      return {
        title: clip(collection.title + " | NTA Knowledge Library", 72),
        description: clip(collection.description, 158),
        canonical: canonicalUrl(canonicalPath),
        noIndex: false,
        routeSpecific: true,
      };
    }
    if (segments.length === 3 && COLLECTION_SEARCH[segments[1]]) {
      const title = LESSON_SEARCH_TITLES[segments[2]] || "Small Business Lesson";
      return {
        title: title + " | NTA Knowledge Library",
        description: "A practical lesson for small-business owners about AI, growth, customer trust, and useful business systems.",
        canonical: canonicalUrl(canonicalPath),
        noIndex: false,
      };
    }
  }

  if (PRIVATE_PREFIXES.some(prefix => canonicalPath === prefix || canonicalPath.startsWith(prefix))) {
    return {
      title: "Private NTA Workspace",
      description: "This NTA workspace is not part of the public website.",
      canonical: canonicalUrl(canonicalPath),
      noIndex: true,
      routeSpecific: true,
    };
  }

  if (PUBLIC_PREFIXES.some(prefix => canonicalPath === prefix || canonicalPath.startsWith(prefix))) {
    const label = canonicalPath === "/" ? "New Tech Advertising" : canonicalPath
      .split("/")
      .filter(Boolean)
      .pop()
      .split("-")
      .map(word => word.charAt(0).toUpperCase() + word.slice(1))
      .join(" ");
    return {
      title: clip(label + " | New Tech Advertising", 72),
      description: DEFAULT_SEO.description,
      canonical: canonicalUrl(canonicalPath),
      noIndex: false,
    };
  }

  return {
    title: "Page Not Found | New Tech Advertising",
    description: "The requested page is not part of the public New Tech Advertising website.",
    canonical: canonicalUrl(canonicalPath),
    noIndex: true,
  };
}

